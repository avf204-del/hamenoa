const PATTERNS: readonly [RegExp, (m: RegExpMatchArray) => string][] = [
  [/^משקל חייב להיות בין 0 ל-(\d+(?:\.\d+)?) ק"ג$/, (m) => `Weight must be between 0 and ${m[1]} kg.`],
  [/^חזרות חייבות להיות בין 0 ל-(\d+)$/, (m) => `Reps must be between 0 and ${m[1]}.`],
  [/^המשקל המקסימלי חייב להיות בין (\d+) ל-(\d+)$/, (m) => `The maximum weight must be between ${m[1]} and ${m[2]}.`],
  [/^יותר מדי אימונים בשעה האחרונה\. נסה שוב בעוד (\d+) דקות\.$/, (m) => `Too many workouts in the last hour. Try again in ${m[1]} minutes.`],
  [/^נשלחו כבר כמה פניות מכאן\. נסה שוב בעוד (\d+) דקות\.$/, (m) => `Several messages were already sent from here. Try again in ${m[1]} minutes.`],
];

export const GENERIC_ERROR_EN = "Something went wrong. Please try again.";

export function localizeApiError(message: string | null | undefined, locale: Locale): string {
  if (!message) return locale === "he" ? "משהו השתבש. אפשר לנסות שוב." : GENERIC_ERROR_EN;
  if (locale === "he") return message;
  if (!/[֐-׿]/.test(message)) return message;
  const exact = EXACT[message.trim()];
  if (exact) return exact;
  for (const [re, fn] of PATTERNS) {
    const m = message.trim().match(re);
    if (m) return fn(m);
  }
  return GENERIC_ERROR_EN;
}
