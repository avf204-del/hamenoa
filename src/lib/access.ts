//
// האסימון חתום וסטייטלס: הוא נושא מזהה ותפקיד, אבל לא יכול לדעת שהבעלים
// ביטל את המשתמש אחרי שהונפק. ‏`currentUser()` כן בודק `revokedAt` מול
// המסד — אלא שהוא רץ רק בשכבות שמעליו, ורכיב מסך שעוטף את הקריאה שלו
// ב-`catch` (מצב-ריק במקום קריסה) בולע גם את החסימה. לכן הבדיקה יושבת גם
// ב-`src/proxy.ts`: המקום היחיד שאף קורא לא יכול לעקוף או לבלוע.
//
// **למה מטמון ולא ביטול מטמון מפורש:** ‏Next מהדר את ה-proxy כחבילה נפרדת
// מקוד השרת, ולכן המודול הזה נטען פעמיים ולכל עותק מטמון משלו. ניסיון
// לנקות את המטמון מראוט הניהול *נראה* עובד ובפועל מנקה את העותק הלא נכון
// (נמדד: הראוט ניקה, וה-proxy המשיך להכניס). מה שמגביל את הסחיפה הוא
// ה-TTL בלבד — אין כאן "ביטול מיידי", יש חלון של שניות, במפורש.

// הייבוא של לקוח המסד נעשה בתוך הפונקציה ולא בראש הקובץ: ה-proxy טוען את
// המודול הזה בכל עלייה, ו-`databaseUrl()` זורק בפרודקשן בלי DATABASE_URL.
// ייבוא סטטי היה הופך פריסה חסרת-הגדרה מ-503 מוסבר (החלטה 20) ל-500 סתום.

/** גג הסחיפה בין ביטול לחסימה בפועל. קצר, כי זו כל ההגנה שיש כאן. */
const TTL_MS = 5_000;
/** קהל של יחידים — התקרה היא רק חגורת ביטחון נגד גדילה בלתי מוגבלת */
const MAX_ENTRIES = 200;

/** רק מי שמותר לו נשמר, ולכן הערך הוא זמן הבדיקה בלבד */
const allowedSince = new Map<string, number>();

/**
 * האם המשתמש עדיין רשאי להיכנס. משתמש שנמחק נחשב חסום, כמו משתמש שבוטל.
 *
 * **רק תשובת "מותר" נכנסת למטמון.** משתמש חסום כמעט לא שולח בקשות, ולכן
 * בדיקה חוזרת אצלו כמעט חינם — ובתמורה *החזרת* גישה תופסת מיד, ולא אחרי
 * חלון המתנה שנראה למשתמש כמו "הכניסה לא עובדת" (נמדד).
 *
 * כשל במסד מחזיר `true` בכוונה ובלי למטמן: השכבה הזו היא מאיץ, לא הסמכות.
 * ‏`currentUser()` בודק שוב מול המסד לפני שמישהו רואה נתונים, ותקלת מסד
 * רגעית לא אמורה לנעול את הבעלים מחוץ לאפליקציה שלו.
 */
export async function userAccessAllowed(userId: string): Promise<boolean> {
  const now = Date.now();
  const checkedAt = allowedSince.get(userId);
  if (checkedAt !== undefined && now - checkedAt < TTL_MS) return true;

  try {
    const { prisma } = await import("@/lib/db");
    const row = await prisma.user.findUnique({
      where: { id: userId },
      select: { revokedAt: true },
    });
    if (row === null || row.revokedAt !== null) {
      allowedSince.delete(userId);
      return false;
    }
    if (allowedSince.size >= MAX_ENTRIES) allowedSince.clear();
    allowedSince.set(userId, now);
    return true;
  } catch (e) {
    console.error("בדיקת ביטול הגישה נכשלה — מעבירים לשכבה הבאה:", e);
    return true;
  }
}
